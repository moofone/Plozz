// Generates Sources/CoreUI/LogoFlagHashes.swift from the system's emoji flags.
// Usage (macOS): cp tools/generate-flag-hashes.swift /tmp/main.swift && swiftc -o /tmp/flaghashes /tmp/main.swift Sources/CoreUI/LogoPerceptualHash.swift && /tmp/flaghashes > Sources/CoreUI/LogoFlagHashes.swift
import AppKit
import CoreGraphics

let countries = [
    "CA", "US", "GB", "MX", "FR", "DE", "ES", "IT", "PT", "IE", "NL", "BE", "CH", "AT", "SE", "NO", "DK", "FI", "PL", "GR",
    "TR", "RU", "UA", "AU", "NZ", "IN", "PK", "CN", "JP", "KR", "BR", "AR", "CO", "CL", "PE", "VE", "ZA", "NG", "EG", "IL",
    "SA", "AE", "IR", "PH", "VN", "TH", "ID", "CU", "DO", "PR", "JM", "HT", "RO", "HU", "CZ", "BG", "RS", "HR"
]

func flag(_ code: String) -> String {
    String(String.UnicodeScalarView(code.unicodeScalars.compactMap { Unicode.Scalar(0x1F1E6 + $0.value - 65) }))
}

func render(_ emoji: String, side: Int) -> CGImage? {
    guard let context = CGContext(
        data: nil, width: side * 2, height: side * 2, bitsPerComponent: 8, bytesPerRow: 0,
        space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
    ) else { return nil }
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: false)
    let font = NSFont(name: "Apple Color Emoji", size: CGFloat(side) * 1.4) ?? NSFont.systemFont(ofSize: CGFloat(side))
    (emoji as NSString).draw(at: CGPoint(x: CGFloat(side) * 0.1, y: CGFloat(side) * 0.3), withAttributes: [.font: font])
    NSGraphicsContext.restoreGraphicsState()
    return context.makeImage()
}

func bitmap(_ width: Int, _ height: Int, _ draw: (CGContext) -> Void) -> CGImage? {
    guard let context = CGContext(
        data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
        space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
    ) else { return nil }
    draw(context)
    return context.makeImage()
}

func fill(_ c: CGContext, _ r: CGFloat, _ g: CGFloat, _ b: CGFloat, _ x: Int, _ y: Int, _ w: Int, _ h: Int) {
    c.setFillColor(red: r, green: g, blue: b, alpha: 1)
    c.fill(CGRect(x: x, y: y, width: w, height: h))
}

// Flat, unwaved versions of the flags providers most often use; emoji flags are shaded and waved.
let flatFlags: [(String, CGImage?)] = [
    ("CA", bitmap(600, 300) { c in
        fill(c, 1, 1, 1, 0, 0, 600, 300); fill(c, 0.85, 0.1, 0.1, 0, 0, 150, 300)
        fill(c, 0.85, 0.1, 0.1, 450, 0, 150, 300); fill(c, 0.85, 0.1, 0.1, 260, 90, 80, 120)
    }),
    ("US", bitmap(570, 300) { c in
        for i in 0..<13 { let red = i % 2 == 0; fill(c, red ? 0.7 : 1, red ? 0.13 : 1, red ? 0.2 : 1, 0, i * 23, 570, 23) }
        fill(c, 0.24, 0.23, 0.43, 0, 300 - 161, 228, 161)
    }),
    ("GB", bitmap(600, 300) { c in
        fill(c, 0.0, 0.14, 0.4, 0, 0, 600, 300)
        c.setStrokeColor(red: 1, green: 1, blue: 1, alpha: 1); c.setLineWidth(50)
        c.move(to: CGPoint(x: 0, y: 0)); c.addLine(to: CGPoint(x: 600, y: 300))
        c.move(to: CGPoint(x: 0, y: 300)); c.addLine(to: CGPoint(x: 600, y: 0)); c.strokePath()
        fill(c, 1, 1, 1, 0, 110, 600, 80); fill(c, 1, 1, 1, 260, 0, 80, 300)
        fill(c, 0.8, 0.07, 0.17, 0, 125, 600, 50); fill(c, 0.8, 0.07, 0.17, 275, 0, 50, 300)
    })
]

print("// Generated by tools/generate-flag-hashes.swift from the system's emoji flags. Do not edit.")
print("// Flags only: no channel, network or league logo belongs in this table.")
print("enum LogoFlagHashes {")
print("    static let table: [(code: String, hash: UInt64)] = [")
for code in countries {
    guard let image = render(flag(code), side: 128), let hash = LogoPerceptualHash.average(of: image) else {
        FileHandle.standardError.write(Data("no hash for \(code)\n".utf8)); continue
    }
    print("        (\"\(code)\", 0x\(String(hash, radix: 16, uppercase: true))),")
}
for (code, image) in flatFlags {
    guard let image, let hash = LogoPerceptualHash.average(of: image) else { continue }
    print("        (\"\(code)\", 0x\(String(hash, radix: 16, uppercase: true))),  // flat")
}
print("    ]")
print("}")
