/// Loading of the evaluation inputs and the Markdown report. Shared by the evaluation test and the standalone driver.
extension LiveTVLogoMatchEvaluator {
    static let sourceNames = ["CA EN", "CA FR", "CA other", "US"]

    static func loadRows(_ path: String) throws -> [Row] {
        try JSONDecoder().decode([Row].self, from: Data(contentsOf: URL(fileURLWithPath: path))).filter { !$0.name.hasPrefix("##") }
    }

    /// TMDB's export: either one JSON object per line, or `{"networks": [...]}` as the app stores it.
    static func loadNetworks(_ path: String) throws -> [TMDbNetworkEntry] {
        let data = try Data(contentsOf: URL(fileURLWithPath: path))
        struct Wrapper: Decodable { let networks: [TMDbNetworkEntry] }
        if let wrapper = try? JSONDecoder().decode(Wrapper.self, from: data) { return wrapper.networks }
        return (String(data: data, encoding: .utf8) ?? "").split(separator: "\n").compactMap {
            try? JSONDecoder().decode(TMDbNetworkEntry.self, from: Data($0.utf8))
        }
    }

    static func loadDetails(_ path: String) -> [Int: NetworkDetail]? {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let raw = try? JSONDecoder().decode([String: NetworkDetail].self, from: data) else { return nil }
        return Dictionary(uniqueKeysWithValues: raw.compactMap { key, value in Int(key).map { ($0, value) } })
    }

    static func loadShowLogos(_ path: String) -> [String: Bool] {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let raw = try? JSONDecoder().decode([String: Bool].self, from: data) else { return [:] }
        return raw
    }

    /// One list per country from a SPARQL answer (item, label, alt label, logo, country).
    static func loadWikidata(_ path: String) -> [String: [WikidataLogoEntry]]? {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let bindings = (root["results"] as? [String: Any])?["bindings"] as? [[String: Any]] else { return nil }
        func value(_ binding: [String: Any], _ name: String) -> String? { (binding[name] as? [String: Any])?["value"] as? String }
        var byItem: [String: (country: String, label: String, file: String, alts: Set<String>)] = [:]
        for binding in bindings {
            guard let item = value(binding, "item")?.split(separator: "/").last.map(String.init),
                  let label = value(binding, "itemLabel"), let logo = value(binding, "logo"),
                  let file = URL(string: logo).flatMap({ $0.path.contains("Special:FilePath/") ? $0.lastPathComponent : nil }),
                  let country = value(binding, "country").flatMap({ $0.hasSuffix("Q16") ? "CA" : $0.hasSuffix("Q30") ? "US" : nil })
            else { continue }
            var entry = byItem[item] ?? (country, label, file, [])
            if let alt = value(binding, "alt") { entry.alts.insert(alt) }
            byItem[item] = entry
        }
        var result: [String: [WikidataLogoEntry]] = [:]
        for (qid, entry) in byItem.sorted(by: { $0.key < $1.key }) {
            result[entry.country, default: []].append(WikidataLogoEntry(qid: qid, label: entry.label, altLabels: entry.alts.sorted(), file: entry.file))
        }
        return result
    }

    /// `{"File name.png": [width, height]}` for Commons raster logos.
    static func loadFileSizes(_ path: String) -> [String: LiveTVLogoSize] {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)),
              let root = try? JSONSerialization.jsonObject(with: data) as? [String: [Int]] else { return [:] }
        return root.compactMapValues { $0.count == 2 ? .raster(width: $0[0], height: $0[1]) : nil }
    }

    static func groupLabel(_ group: String) -> String {
        let label = group.split(separator: "|", maxSplits: 1).last.map(String.init) ?? group
        return label.decomposedStringWithCompatibilityMapping.replacingOccurrences(of: #"\s+(HD|RAW|60fps|/)+.*$"#, with: "", options: .regularExpression)
            .trimmingCharacters(in: .whitespaces)
    }

    // MARK: Report

    static func report(_ evaluation: Evaluation, rowCount: Int) -> String {
        let results = evaluation.results
        func pct(_ value: Int, of total: Int) -> String { String(format: "%d (%.1f%%)", value, total == 0 ? 0 : Double(value) * 100 / Double(total)) }
        let realLogoLayers: Set<Layer> = [.curated, .tmdb, .showLogo, .wikidata, .xmltv]
        var out = "# Logo matching report (round 2)\n\nGenerated by `LiveTVLogoMatchEvaluator` on \(rowCount) channels (section markers excluded).\n\n"
        let provisional = results.filter(\.provisional).count
        out += "TMDB network origin countries and logo presence come from \(evaluation.missingDetailIDs.isEmpty ? "real TMDB details" : "TMDB details, with \(evaluation.missingDetailIDs.count) proposed networks lacking details (their origin is assumed to be the channel's own; \(provisional) channels depend on that)").\n\n"

        out += "## Coverage by source and kind\n\nA channel \"has a real logo\" when a curated, TMDB, Wikidata or XMLTV icon is available; the playlist provider's own logo is never drawn, so a channel with only that is a text plate. Events are not channels and are excluded from the rates.\n\n"
        out += "| Source | Kind | Channels | Real logo | TMDB/curated/Wikidata | Text plate |\n|---|---|---|---|---|---|\n"
        for source in sourceNames {
            for kind in [LiveTVChannelKind.linear, .showLoop, .fast, .event] {
                let group = results.filter { $0.source == source && $0.kind == kind }
                guard !group.isEmpty else { continue }
                if kind == .event { out += "| \(source) | event | \(group.count) | – | – | – |\n"; continue }
                let real = group.filter { realLogoLayers.contains($0.layer) }.count
                let matched = group.filter { [.curated, .tmdb, .showLogo, .wikidata].contains($0.layer) }.count
                let text = group.filter { $0.layer == .text }.count
                out += "| \(source) | \(kind.rawValue) | \(group.count) | \(pct(real, of: group.count)) | \(pct(matched, of: group.count)) | \(pct(text, of: group.count)) |\n"
            }
        }
        let linear = results.filter { $0.kind == .linear }
        out += "\nLinear channels with a real logo: CA EN \(pct(linear.filter { $0.source == "CA EN" && realLogoLayers.contains($0.layer) }.count, of: linear.filter { $0.source == "CA EN" }.count)), "
        out += "CA FR \(pct(linear.filter { $0.source == "CA FR" && realLogoLayers.contains($0.layer) }.count, of: linear.filter { $0.source == "CA FR" }.count)), "
        out += "US \(pct(linear.filter { $0.source == "US" && realLogoLayers.contains($0.layer) }.count, of: linear.filter { $0.source == "US" }.count)), "
        out += "CA other \(pct(linear.filter { $0.source == "CA other" && realLogoLayers.contains($0.layer) }.count, of: linear.filter { $0.source == "CA other" }.count)).\n"

        out += "\n## Crisp at 4K\n\nShare of linear channels with a real logo whose chosen image is a vector or at least as large as the box along its limiting axis: **guide** 328 × 104 px, **panel** 702 × 248 px. An unmeasured Commons raster counts as not crisp.\n\n"
        out += "| Source | Real logo | Crisp, guide | Crisp, panel | Vector |\n|---|---|---|---|---|\n"
        for source in ["CA EN", "CA FR", "CA other", "US"] {
            let real = linear.filter { $0.source == source && realLogoLayers.contains($0.layer) }
            func crisp(_ target: LiveTVLogoTarget) -> Int { real.filter { $0.size.map { LiveTVLogoQuality.isCrisp($0, for: target) } ?? false }.count }
            out += "| \(source) | \(real.count) | \(pct(crisp(.guide), of: real.count)) | \(pct(crisp(.hero), of: real.count)) | \(pct(real.filter { $0.size == .vector }.count, of: real.count))|\n"
        }
        let soft = linear.filter { ($0.source == "CA EN" || $0.source == "CA FR") && realLogoLayers.contains($0.layer) && !($0.size.map { LiveTVLogoQuality.isCrisp($0, for: .hero) } ?? false) }
        out += "\nCA EN/FR linear brands still below the panel size (\(soft.count) channels):\n\n"
        for (layer, items) in Dictionary(grouping: soft, by: \.layer).sorted(by: { $0.key.rawValue < $1.key.rawValue }) {
            let names = Set(items.map { LiveTVLogoPlaceholders.brandKey($0.row.name) }).sorted()
            out += "- \(layer.rawValue) (\(items.count)): \(names.prefix(60).joined(separator: ", "))\n"
        }

        out += "\n## 24/7 single-show loops by provider group\n\n| Group | Channels | With a show logo | Text |\n|---|---|---|---|\n"
        let loops = results.filter { $0.kind == .showLoop }
        for (group, items) in Dictionary(grouping: loops, by: { $0.row.groups.first.map { LiveTVLogoMatchEvaluator.groupLabel($0) } ?? "" }).sorted(by: { $0.value.count > $1.value.count }).prefix(14) {
            out += "| \(group) | \(items.count) | \(pct(items.filter { $0.layer == .showLogo }.count, of: items.count)) | \(items.filter { $0.layer == .text }.count) |\n"
        }
        out += "\n## What each layer newly covers (waterfall order, non-event channels)\n\n| Layer | CA EN | CA FR | CA other | US | Total |\n|---|---|---|---|---|---|\n"
        let nonEvent = results.filter { $0.kind != .event }
        for layer in Layer.allCases where layer != .event {
            let counts = sourceNames.map { name in nonEvent.filter { $0.source == name && $0.layer == layer }.count }
            out += "| \(layer.rawValue) | \(counts.map(String.init).joined(separator: " | ")) | \(counts.reduce(0, +)) |\n"
        }
        out += "| (guide ID present in export) | – | – | – | – | \(nonEvent.filter { !($0.row.guideID ?? "").isEmpty }.count) |\n"

        out += "\n## TMDB/curated matches by rule\n\n| Rule | CA EN | CA FR | CA other | US | Total | of which provisional |\n|---|---|---|---|---|---|---|\n"
        let ruleOrder: [LiveTVTMDbMatchRule] = [.curated, .exactName, .alternateName, .alias, .collapsedName, .family, .groupBrand, .affiliate]
        for rule in ruleOrder {
            let counts = sourceNames.map { name in results.filter { $0.source == name && $0.rule == rule && $0.layer != .text }.count }
            let prov = results.filter { $0.rule == rule && $0.provisional && $0.layer != .text }.count
            out += "| \(rule.rawValue) | \(counts.map(String.init).joined(separator: " | ")) | \(counts.reduce(0, +)) | \(prov) |\n"
        }

        // Remaining text plates and unmatched by brand.
        let remaining = Dictionary(grouping: nonEvent.filter { $0.layer == .text }, by: \.brand)
            .map { (brand: $0.key, count: $0.value.count, kinds: Set($0.value.map(\.kind.rawValue)).sorted().joined(separator: "/"), example: $0.value[0].row.name) }
            .sorted { ($0.count, $1.brand) > ($1.count, $0.brand) }
        out += "\n## Text plates by brand (no logo at all), top 80\n\n\(nonEvent.filter { $0.layer == .text }.count) channels end as text.\n\n| Brand key | Channels | Kind | Example |\n|---|---|---|---|\n"
        for item in remaining.prefix(80) { out += "| \(item.brand) | \(item.count) | \(item.kinds) | \(item.example.replacingOccurrences(of: "|", with: "¦")) |\n" }

        let linearText = Dictionary(grouping: linear.filter { $0.layer == .text && $0.source != "CA other" }, by: \.brand)
            .map { (brand: $0.key, count: $0.value.count, example: $0.value[0].row.name) }.sorted { ($0.count, $1.brand) > ($1.count, $0.brand) }
        out += "\n## Linear channels left on text (CA EN, CA FR, US), top 60\n\n| Brand key | Channels | Example |\n|---|---|---|\n"
        for item in linearText.prefix(60) { out += "| \(item.brand) | \(item.count) | \(item.example.replacingOccurrences(of: "|", with: "¦")) |\n" }

        out += "\n## Ties (different brands, left unmatched)\n\n"
        let ties = Dictionary(grouping: results.filter { !$0.tie.isEmpty }, by: \.brand)
        for (brand, items) in ties.sorted(by: { $0.key < $1.key }).prefix(40) { out += "- `\(brand)` (\(items.count) channels): \(items[0].tie.joined(separator: ", "))\n" }

        // Samples for hand review: newly accepted via the round-2 rules.
        func isNew(_ result: Result) -> Bool {
            switch result.rule { case .collapsedName?, .family?, .groupBrand?, .affiliate?, .curated?: true; default: result.layer == .wikidata }
        }
        let accepted = results.filter { [.curated, .tmdb, .wikidata].contains($0.layer) && isNew($0) }
        var generator = SeededGenerator(seed: 458)
        func sample(_ pool: [Result], _ count: Int) -> [Result] {
            var pool = pool
            var picked: [Result] = []
            while picked.count < count, !pool.isEmpty { picked.append(pool.remove(at: Int.random(in: 0..<pool.count, using: &generator))) }
            return picked
        }
        func table(_ items: [Result]) -> String {
            var text = "| Channel | Matched to | Layer / rule |\n|---|---|---|\n"
            for item in items {
                text += "| \(item.row.name.replacingOccurrences(of: "|", with: "¦")) | \(item.matchedName ?? "") | \(item.layer.rawValue) \(item.rule?.rawValue ?? "")\(item.provisional ? " (provisional)" : "") |\n"
            }
            return text
        }
        out += "\n## 40 CA matches accepted through the round-2 rules (seed 458)\n\n" + table(sample(accepted.filter { $0.source != "US" }, 40))
        out += "\n## 40 US matches accepted through the round-2 rules (seed 458)\n\n" + table(sample(accepted.filter { $0.source == "US" }, 40))
        let familyOnly = results.filter { $0.rule == .family }
        out += "\n## 40 family-rule matches (rule 2 alone adds \(familyOnly.count) channels)\n\n" + table(sample(familyOnly, 40))

        out += "\n## Performance (this run's build configuration)\n\nMatching of \(rowCount) channels, all layers: \(evaluation.elapsed).\n"
        return out
    }

    /// Reproducible sampling for the manual precision check.
    struct SeededGenerator: RandomNumberGenerator {
        var state: UInt64
        init(seed: UInt64) { state = seed &+ 0x9E3779B97F4A7C15 }
        mutating func next() -> UInt64 {
            state = state &+ 0x9E3779B97F4A7C15
            var z = state
            z = (z ^ (z >> 30)) &* 0xBF58476D1CE4E5B9
            z = (z ^ (z >> 27)) &* 0x94D049BB133111EB
            return z ^ (z >> 31)
        }
    }
}

extension LiveTVLogoMatchEvaluator {
    /// Every channel left on text, one line each: source, kind, brand key, name. Used to build the curated table.
    static func textPlateListing(_ evaluation: Evaluation) -> String {
        evaluation.results.filter { $0.kind != .event && $0.layer == .text }
            .map { "\($0.source)\t\($0.kind.rawValue)\t\($0.brand)\t\($0.row.name)" }.joined(separator: "\n")
    }
}
